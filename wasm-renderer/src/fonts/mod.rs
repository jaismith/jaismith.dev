//! Embedded FIGlet-style fonts for ASCII art text rendering

/// A FIGlet character definition
#[derive(Clone, Debug)]
pub struct FigChar {
    /// Lines of the character (each line is a string of characters)
    pub lines: Vec<String>,
    /// Width of this character
    pub width: usize,
}

/// A FIGlet font
#[derive(Clone, Debug)]
pub struct FigFont {
    /// Height of the font in lines
    pub height: usize,
    /// Baseline offset from top
    pub baseline: usize,
    /// Character definitions (ASCII 32-126)
    pub chars: Vec<Option<FigChar>>,
    /// Hard blank character
    pub hardblank: char,
}

impl FigFont {
    /// Get a character definition
    pub fn get_char(&self, c: char) -> Option<&FigChar> {
        let idx = c as usize;
        if idx >= 32 && idx <= 126 {
            self.chars.get(idx - 32).and_then(|o| o.as_ref())
        } else {
            None
        }
    }

    /// Calculate the width of rendered text
    pub fn text_width(&self, text: &str) -> usize {
        text.chars()
            .filter_map(|c| self.get_char(c))
            .map(|fc| fc.width)
            .sum()
    }
}

